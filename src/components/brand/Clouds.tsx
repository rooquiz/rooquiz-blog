import type { CSSProperties } from 'react'

/**
 * 英雄区底部的云层。三层不同深浅的圆丘剪影，层层往前推，最前面那层就是 --paper ——
 * 于是天空不是「停」在某条边上，而是被纸从底下漫上来盖住，天与正文之间没有硬边。
 *
 * ── 画布是定宽的，不随视口拉伸 ──
 * viewBox 5120 宽，CSS 也给 5120px（见 sky.css 的 .sky__clouds），居中放置、
 * 两侧溢出由 .sky 的 overflow: clip 裁掉。这一条是这套云的关键：
 * 山丘的物理尺寸因此恒定（波长约 1200px），窄屏只是少看见几座，而不是把同样多的
 * 山丘挤进更小的宽度里。早先按 width:100% 拉伸过一版，1440 屏上七座峰挤在一起，
 * 顶端连成一条规则的波浪 —— 读出来是扇贝花边，不是云。
 *
 * ── 圆丘用「半宽 + 峰高」描述，不是「圆心 + 半径」──
 * 想要的是很扁的帽子（半宽 600、峰高 180 那种），换算成圆是半径 1100 出头、
 * 圆心沉在地平线下方 900 —— 那三个数手调起来毫无手感。所以这里写的是直观的
 * (x, w, h)，圆心与半径由 hillToCircle() 反算。
 *
 * ── 谷的位置和袋鼠绑定 ──
 * 三层的峰高都在 x≈2800（视口中心右侧约 240，正是袋鼠与彩虹拱所在）附近降到最低，
 * 天际线于是在那里让出一片开阔的天，拱门衬在里面而不是被云埋掉。
 *
 * 注意谷是**调制峰高**做出来的，不是留空档。试过在那一段干脆不排山丘：
 * 天际线塌回平直的地平线，两侧巨峰的斜边在这个尺度下几乎是直线，
 * 整个谷读成一个尖锐的三角楔子，像一束聚光而不是云。山丘连续排布、
 * 只让高度从两侧向中间递减，得到的才是一条连绵起伏、谷宽而缓的天际线。
 *
 * 三层的地平线都压在画布底部附近（396 / 420 / 438，画布高 456），起伏全靠峰高的
 * 落差撑出来 —— 谷底永远低不过地平线，地平线定高了，谷再怎么调也会把拱门腰斩。
 *
 * 山丘的间距（≈580）比半宽（≈500）小，保证处处相交；相邻两座之和一旦小于间距，
 * 谷底会摊平成一条水平线，山丘之间露出「台阶」。
 *
 * 视口只看得见这块 5120 画布的中间一段（1440 屏对应 viewBox 的 1840…3280），
 * 所以谷两侧的峰必须落在这个窗口里，否则整屏只剩一条光溜溜的斜坡。
 * 改袋鼠的横向偏移（--hero-shift）时，峰高的低点要跟着挪。
 *
 * ── 相邻圆丘必须相交 ──
 * 每一层是「一条铺满下半部的矩形 + 骑在它上沿的一排圆」，同色不透明填充，
 * 相交处自然合并。只要相邻两座的半宽之和大于它们的间距，谷底就落在地平线之上、
 * 且是一段圆弧；一旦不相交，谷底会摊平成一条水平线，山丘之间露出「台阶」。
 */

/** 峰心 x、半宽、峰高（相对该层地平线） */
type Hill = [x: number, w: number, h: number]

interface Layer {
  fill: string
  /** 这一层的地平线 */
  base: number
  hills: Hill[]
  /** 动效：横向漂移的幅度（viewBox 单位 = px，因为是 1:1）与一个来回的时长 */
  drift: number
  duration: string
}

/**
 * 由 (半宽 w, 峰高 h) 反算出过 (±w, 0) 与 (0, h) 三点的圆。
 * r = (w² + h²) / 2h，圆心沉在地平线下方 r - h。
 */
function hillToCircle(w: number, h: number) {
  const r = (w * w + h * h) / (2 * h)
  return { r, drop: r - h }
}

const VIEW_W = 5120
const VIEW_H = 456

/*
 * 三层的地平线依次下移、山丘依次变矮 —— 远处的山头高而缓、近处的低而碎，
 * 这样才有纵深。x 与尺寸都刻意不等距：等距等大的山丘顶端连起来是规则的正弦波。
 * 每层左右各多排一座（x 为负 / 超过 5120），免得超宽屏上两端露出天空。
 */
